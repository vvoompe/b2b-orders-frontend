/**
 * Спільні для таблиці й карток означення станів панелі списку замовлень
 * (див. Рисунок 3 у Розділі 1: скелетон, дані, порожній результат, помилка).
 */

export type OrdersViewState = 'loading' | 'success' | 'empty' | 'error';

export interface OrdersEmptyContent {
  title: string;
  description: string;
  hint: string;
}

/**
 * Порожній результат має різні пояснення залежно від причини: «немає даних
 * узагалі» і «фільтри нічого не знайшли» - це різні ситуації й різні поради.
 */
export function emptyContentFor(hasFilters: boolean): OrdersEmptyContent {
  if (hasFilters) {
    return {
      title: 'За вибраними умовами замовлень не знайдено',
      description: 'Жодне замовлення не відповідає поточному набору фільтрів.',
      hint: 'Спробуйте розширити період, збільшити діапазон суми або скинути фільтри.',
    };
  }

  return {
    title: 'Замовлень поки немає',
    description: 'Для вашого облікового запису ще не створено жодного замовлення.',
    hint: 'Замовлення з’являться тут автоматично після першої синхронізації з CRM.',
  };
}
